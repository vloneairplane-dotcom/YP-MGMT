_last: dict[str, int] = {}


def generate(category: str, avoid_repeat: bool = True) -> str:
    """Return one idea string for the given category key."""
    bank = BANKS.get(category, CONCEPTS)
    if not avoid_repeat or len(bank) < 2:
        return random.choice(bank)
    idx = _last.get(category, -1)
    new_idx = idx
    while new_idx == idx:
        new_idx = random.randrange(len(bank))
    _last[category] = new_idx
    return bank[new_idx]


def full_brief() -> dict[str, str]:
    """Mix one idea from every lane into a complete project brief."""
    return {key: generate(key) for key in BANKS}


def category_label(key: str) -> tuple[str, str]:
    meta = IDEA_CATEGORIES.get(key, {"label": key, "emoji": "💡"})
    return meta["emoji"], meta["label"]
